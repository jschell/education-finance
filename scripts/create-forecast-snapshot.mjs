import {readFileSync,writeFileSync,readdirSync}from 'node:fs';
import {execFileSync}from 'node:child_process';
import {createHash}from 'node:crypto';
import {ACTIVE_CALIBRATION_FILE}from '../site/js/release.js';
import {createSnapshot,validDate}from './calibration/prospective.mjs';
const args=process.argv.slice(2),value=name=>{const i=args.indexOf(name);return i<0?null:args[i+1];};
const asOf=value('--as-of'),output=value('--output'),activePath='site/data/'+ACTIVE_CALIBRATION_FILE,bundlePath=value('--bundle')||activePath;
if(!validDate(asOf)||!output)throw Error('Use --as-of YYYY-MM-DD --output NEW_FILE.json [--bundle PATH --allow-nonproduction-bundle]');
const b=JSON.parse(readFileSync(bundlePath)),active=JSON.parse(readFileSync(activePath));
const production=b.sha256===active.sha256;
if(!production&&!args.includes('--allow-nonproduction-bundle'))throw Error('Nonproduction bundle requires --allow-nonproduction-bundle.');
const commit=value('--source-commit')||process.env.GITHUB_SHA||execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
if(!/^[a-f0-9]{40}$/.test(commit))throw Error('Valid source commit required.');
const sourcePaths=[...readdirSync('site/js').filter(p=>p.endsWith('.js')).sort().map(p=>'site/js/'+p),bundlePath,'scripts/create-forecast-snapshot.mjs','scripts/calibration/prospective.mjs','docs/forecast-calibration-plan.md'];
const sha=x=>createHash('sha256').update(x).digest('hex');
const sourceHashes=Object.fromEntries(sourcePaths.map(p=>{
 const actual=readFileSync(p),recorded=execFileSync('git',['show',commit+':'+p],{maxBuffer:16*1024*1024});
 if(sha(actual)!==sha(recorded))throw Error('Source bytes differ from claimed commit: '+p);
 return [p,sha(actual)];
}));
const snapshot=createSnapshot({bundle:b,asOf,sourceCommit:commit,sourceHashes,production});
writeFileSync(output,JSON.stringify(snapshot)+'\n',{flag:'wx'});
console.log(JSON.stringify({path:output,sha256:snapshot.sha256,bundleId:b.id,model:snapshot.modelVersion,production,forecasts:snapshot.forecasts.length}));
